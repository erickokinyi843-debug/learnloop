const subjectGuideCache = new Map();
let quizCompletions = {};

function topicQuizId(grade, subject, index) {
  return `${grade}::${subject}::${index + 1}`;
}

async function loadQuizCompletions() {
  quizCompletions = {};
  if (activeAccount?.role !== "student") return;
  try {
    const result = await api("/api/student/progress");
    quizCompletions = result.quizCompletions || {};
  } catch (error) {
    quizCompletions = {};
  }
}

async function fetchSubjectGuide(grade, subject) {
  const key = `${grade}::${subject}`;
  if (subjectGuideCache.has(key)) return subjectGuideCache.get(key);
  const guide = await api(
    `/api/curriculum/subject?grade=${encodeURIComponent(grade)}&subject=${encodeURIComponent(subject)}`
  );
  subjectGuideCache.set(key, guide);
  return guide;
}

function buildTopicQuiz(unit, grade, subject, index) {
  const questions = Array.isArray(unit.quiz) ? unit.quiz : [];
  if (!questions.length) return null;
  const topicId = topicQuizId(grade, subject, index);
  const completed = quizCompletions[topicId];
  const block = document.createElement("section");
  block.className = "topic-quiz";
  block.dataset.topicQuiz = topicId;

  const header = document.createElement("div");
  header.className = "topic-quiz-header";
  const heading = document.createElement("strong");
  heading.textContent = "Topic quiz";
  const meta = document.createElement("span");
  meta.className = "topic-quiz-meta";
  meta.textContent = `${questions.length} questions · multiple choice & true/false`;
  header.append(heading, meta);
  block.append(header);

  if (completed) {
    const badge = document.createElement("p");
    badge.className = "topic-quiz-badge";
    badge.textContent = `✓ Completed · best score ${completed.score}/${completed.total}`;
    block.append(badge);
  }

  questions.forEach((question, questionIndex) => {
    const card = document.createElement("div");
    card.className = "quiz-question";
    card.dataset.answered = completed ? "true" : "false";
    const prompt = document.createElement("p");
    prompt.className = "quiz-prompt";
    prompt.textContent = `${questionIndex + 1}. ${question.prompt}`;
    card.append(prompt);
    if (question.type === "true_false") {
      const tag = document.createElement("span");
      tag.className = "quiz-tag";
      tag.textContent = "True or false";
      prompt.append(" ", tag);
    }
    const options = document.createElement("div");
    options.className = "quiz-options";
    (question.options || []).forEach((optionText, optionIndex) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "quiz-option";
      button.textContent = optionText;
      button.dataset.correct = optionIndex === question.answer ? "true" : "false";
      if (completed) {
        button.disabled = true;
        if (optionIndex === question.answer) button.classList.add("correct");
      }
      options.append(button);
    });
    card.append(options);
    block.append(card);
  });

  const progress = document.createElement("p");
  progress.className = "topic-quiz-progress";
  progress.dataset.quizProgress = topicId;
  block.append(progress);

  if (!completed) {
    const submit = document.createElement("button");
    submit.type = "button";
    submit.className = "topic-quiz-submit";
    submit.dataset.quizSubmit = topicId;
    submit.textContent = "Submit quiz for XP";
    submit.disabled = true;
    block.append(submit);
    const result = document.createElement("p");
    result.className = "topic-quiz-result";
    result.dataset.quizResult = topicId;
    block.append(result);
  }
  return block;
}

function updateQuizProgress(block) {
  const questions = [...block.querySelectorAll(".quiz-question")];
  const answered = questions.filter((question) => question.dataset.answered === "true");
  const progress = block.querySelector("[data-quiz-progress]");
  const submit = block.querySelector("[data-quiz-submit]");
  if (progress) {
    progress.textContent = answered.length === questions.length
      ? "All questions answered — submit to save your score."
      : `Answered ${answered.length} of ${questions.length}.`;
  }
  if (submit) submit.disabled = answered.length !== questions.length;
}

function handleQuizOption(option) {
  const question = option.closest(".quiz-question");
  if (!question || question.dataset.answered === "true") return;
  question.dataset.answered = "true";
  question.querySelectorAll(".quiz-option").forEach((button) => {
    button.disabled = true;
    if (button.dataset.correct === "true") button.classList.add("correct");
  });
  const correct = option.dataset.correct === "true";
  if (!correct) option.classList.add("incorrect");
  question.classList.add(correct ? "is-correct" : "is-incorrect");
  const block = option.closest(".topic-quiz");
  if (block) updateQuizProgress(block);
}

async function submitTopicQuiz(button) {
  const block = button.closest(".topic-quiz");
  if (!block) return;
  const topicId = block.dataset.topicQuiz;
  const questions = [...block.querySelectorAll(".quiz-question")];
  const score = questions.filter((question) => question.classList.contains("is-correct")).length;
  const total = questions.length;
  button.disabled = true;
  button.textContent = "Saving…";
  const result = block.querySelector("[data-quiz-result]");
  let awardedXp = 0;
  let alreadyCompleted = false;
  if (activeAccount?.role === "student") {
    try {
      const response = await api("/api/student/activity", {
        method: "POST",
        body: JSON.stringify({ activity: "topic_quiz", topicId, score, total })
      });
      activeAccount = response.user;
      updateStudentDashboard(activeAccount);
      quizCompletions[topicId] = { score: response.score, total: response.total };
      awardedXp = response.awardedXp;
      alreadyCompleted = response.alreadyCompleted;
      await loadStudentResources();
    } catch (error) {
      showToast(error.message);
      button.disabled = false;
      button.textContent = "Submit quiz for XP";
      return;
    }
  } else {
    quizCompletions[topicId] = { score, total };
    alreadyCompleted = true;
  }
  button.hidden = true;
  if (result) {
    result.textContent = awardedXp
      ? `Score saved: ${score}/${total} correct · +${awardedXp} XP`
      : `Score saved: ${score}/${total} correct${alreadyCompleted ? " (already completed — no new XP)" : ""}`;
  }
  showToast(awardedXp
    ? `Topic quiz complete — ${score}/${total} correct, +${awardedXp} XP!`
    : `Topic quiz complete — ${score}/${total} correct.`);
}

