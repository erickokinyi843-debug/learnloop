  function renderSubjectResources() {
    const list = document.querySelector("#subject-resource-list");
    list.replaceChildren();
    const resources = papers.filter(
      (paper) => paper.grade === managedSubject.grade && paper.subject === managedSubject.subject
    );
    if (!resources.length) {
      const empty = document.createElement("li");
      empty.className = "student-resource-empty";
      empty.textContent = "No notes or exams have been added for this subject yet.";
      list.append(empty);
      return;
    }
    resources.forEach((paper) => {
      const item = document.createElement("li");
      item.className = "paper-item";
      const icon = document.createElement("span");
      icon.className = "paper-file-icon";
      icon.textContent = paper.name.split(".").pop().toUpperCase().slice(0, 3);
      const details = document.createElement("span");
      details.className = "paper-details";
      const name = document.createElement("strong");
      name.textContent = paper.name;
      const meta = document.createElement("small");
      meta.textContent = `${paper.kind} · ${formatFileSize(paper.size)}`;
      details.append(name, meta);
      const download = document.createElement("a");
      download.href = apiUrl(`/api/resources/${encodeURIComponent(paper.id)}/download`);
      download.textContent = "Download";
      item.append(icon, details, download);
      if (activePermissions.includes("resources")) {
        const remove = document.createElement("button");
        remove.type = "button";
        remove.className = "paper-remove";
        remove.dataset.removeResource = paper.id;
        remove.setAttribute("aria-label", `Remove ${paper.name}`);
        remove.textContent = "×";
        item.append(remove);
      }
      list.append(item);
    });
  }

