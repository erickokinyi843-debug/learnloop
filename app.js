async function loadAdminData() {
  try {
    const access = await api("/api/admin/access");
    activePermissions = access.permissions;
    adminGrades = access.grades;
    document.querySelectorAll("[data-admin-permission]").forEach((panel) => {
      panel.hidden = !activePermissions.includes(panel.dataset.adminPermission);
    });
    restrictAdminGrades();
    configureAdminSubjectGrades();
    let overview = null;
    if (activePermissions.includes("overview")) {
      overview = await api("/api/admin/overview");
      document.querySelector("#admin-student-count").textContent = overview.studentCount.toLocaleString();
      document.querySelector("#admin-activity-count").textContent = overview.activityCount.toLocaleString();
      document.querySelector("#admin-study-time").innerHTML = `${overview.learningMinutes.toLocaleString()} <small>mins</small>`;
      renderAdminActivity(overview.recentActivity);
    }
    if (activePermissions.includes("learners")) {
      const students = overview ? overview.students : (await api("/api/admin/students")).students;
      renderLearners(students);
    }
    if (activePermissions.includes("groups")) await loadAdminGroups();
    if (activePermissions.includes("resources")) {
      papers = (await api("/api/resources")).resources;
      renderPapers();
      if (activePermissions.includes("overview")) renderStudyMaterialsOverview();
    }
    if (activePermissions.includes("settings") && overview) {
      document.querySelectorAll("[data-setting]").forEach((input) => {
        input.checked = Boolean(overview.settings[input.dataset.setting]);
      });
    }
    if (activePermissions.includes("competitions")) await renderCompetition();
    if (activePermissions.includes("classes")) await loadAdminClasses();
    if (activePermissions.includes("delegates")) {
      renderDelegates(await api("/api/admin/delegates"));
    }
  } catch (error) {
    showToast(error.message);
  }
}

