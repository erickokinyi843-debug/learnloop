async function api(path, options = {}) {
  let response;
  try {
    response = await fetch(apiUrl(path), {
      credentials: "include",
      ...options,
      headers: {
        ...(options.body instanceof FormData ? {} : { "Content-Type": "application/json" }),
        ...options.headers
      }
    });

    document.querySelector("#subject-resource-form").addEventListener("submit", async (event) => {
      event.preventDefault();
      const form = event.currentTarget;
      const submit = form.querySelector('button[type="submit"]');
      const files = [...document.querySelector("#subject-resource-files").files];
      if (!managedSubject || !files.length) return;
      submit.disabled = true;
      let added = 0;
      try {
        for (const file of files) {
          const formData = new FormData();
          formData.append("kind", document.querySelector("#subject-resource-kind").value);
          formData.append("grade", managedSubject.grade);
          formData.append("subject", managedSubject.subject);
          formData.append("file", file);
          try {
            await api("/api/admin/resources", { method: "POST", body: formData });
            added += 1;
          } catch (error) {
            showToast(`${file.name}: ${error.message}`);
          }
        }
        if (added) {
          papers = (await api("/api/resources")).resources;
          renderPapers();
          renderSubjectResources();
          form.reset();
          showToast(`${added} resource${added === 1 ? "" : "s"} uploaded to ${managedSubject.subject}.`);
        }
      } catch (error) {
        showToast(error.message);
      } finally {
        submit.disabled = false;
      }
    });

    document.querySelector("#subject-resource-list").addEventListener("click", async (event) => {
      const button = event.target.closest("[data-remove-resource]");
      if (!button) return;
      button.disabled = true;
      try {
        await api(`/api/admin/resources/${encodeURIComponent(button.dataset.removeResource)}`, { method: "DELETE" });
        papers = (await api("/api/resources")).resources;
        renderPapers();
        renderSubjectResources();
        showToast("Resource removed from the server.");
      } catch (error) {
        showToast(error.message);
        button.disabled = false;
      }
    });

    document.querySelector("#video-dialog").addEventListener("close", () => {
      document.querySelector("#video-player").src = "";
    });
  } catch (error) {
    throw new Error(apiBaseUrl
      ? "Cannot reach the Learnloop API. Check its URL and confirm its CORS settings allow this website."
      : "Cannot reach the Learnloop server. Start it with `python server.py` and try again.");
  }
  const result = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(result.error || `Request failed (${response.status}).`);
  return result;
}

function replaceOptions(select, values, selectedValue = "") {
  select.replaceChildren();
  values.forEach((value) => {
    const option = document.createElement("option");
    option.value = value;
    option.textContent = value;
    select.append(option);
  });
  if (selectedValue && values.includes(selectedValue)) select.value = selectedValue;
}

function replaceSuggestions(datalist, values) {
  datalist.replaceChildren();
  values.forEach((value) => {
    const option = document.createElement("option");
    option.value = value;
    datalist.append(option);
  });
}

function populateSubjects(select, grade, selectedValue = "") {
  const subjects = curriculum.subjects[grade] || [];
  const allKnownSubjects = Object.values(curriculum.subjects).flat();
  replaceSuggestions(document.querySelector(`#${select.id}-suggestions`), subjects);
  if (!select.value || allKnownSubjects.includes(select.value)) {
    select.value = subjects.includes(selectedValue) ? selectedValue : subjects[0] || "";
  }
}

