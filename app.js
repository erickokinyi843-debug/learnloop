async function renderCompetition() {
  if (activeAccount?.role !== "admin") return;
  const period = document.querySelector("#competition-period").value;
  try {
    const result = await api(`/api/admin/leaderboard?period=${encodeURIComponent(period)}`);
    competitionRows = result.standings;
  } catch (error) {
    showToast(error.message);
    return;
  }
  const gradeSelect = document.querySelector("#scoreboard-grade");
  const selectedGrade = gradeSelect.value;
  const grades = [...new Set(competitionRows.map((learner) => learner.grade).filter(Boolean))]
    .sort((a, b) => a.localeCompare(b));
  gradeSelect.replaceChildren(new Option("All grades", "all"));
  grades.forEach((grade) => gradeSelect.add(new Option(grade, grade)));
  if (grades.includes(selectedGrade)) gradeSelect.value = selectedGrade;
  renderCompetitionTable();
}

function visibleCompetitionRows() {
  const search = document.querySelector("#scoreboard-search").value.trim().toLocaleLowerCase();
  const grade = document.querySelector("#scoreboard-grade").value;
  const { key, direction } = competitionSort;
  return competitionRows
    .filter((learner) => (
      (grade === "all" || learner.grade === grade)
      && (!search || learner.name.toLocaleLowerCase().includes(search))
    ))
    .sort((a, b) => {
      const property = key === "lessons" ? "lessons_completed" : key;
      const left = a[property];
      const right = b[property];
      const comparison = typeof left === "string" ? left.localeCompare(right) : left - right;
      return comparison * direction;
    });
}

function renderCompetitionTable() {
  const rows = visibleCompetitionRows();
  const xpTotal = rows.reduce((total, learner) => total + learner.points, 0);
  const badgeTotal = rows.reduce((total, learner) => total + learner.achievement_count, 0);
  const leader = [...rows].sort((a, b) => b.points - a.points || a.name.localeCompare(b.name))[0];
  document.querySelector("#scoreboard-learner-count").textContent = rows.length.toLocaleString();
  document.querySelector("#scoreboard-xp-total").textContent = xpTotal.toLocaleString();
  document.querySelector("#scoreboard-badge-total").textContent = badgeTotal.toLocaleString();
  document.querySelector("#scoreboard-leader").textContent = leader
    ? `${leader.name} · ${leader.points.toLocaleString()} XP`
    : "—";
  const tableBody = document.querySelector("#competition-rows");
  tableBody.replaceChildren();
  if (rows.length === 0) {
    const emptyRow = document.createElement("tr");
    const emptyCell = document.createElement("td");
    emptyCell.colSpan = 5;
    emptyCell.className = "table-empty";
    emptyCell.textContent = competitionRows.length
      ? "No learners match these filters."
      : "Student standings will appear after the first learning activity.";
    emptyRow.append(emptyCell);
    tableBody.append(emptyRow);
    return;
  }
  rows.forEach((learner, index) => {
    const row = document.createElement("tr");
    const rank = document.createElement("td");
    const rankBadge = document.createElement("span");
    rankBadge.className = `table-rank ${rankColors[index] || "rank-other"}`;
    rankBadge.textContent = String(index + 1);
    rank.append(rankBadge);
    const name = document.createElement("td");
    const learnerWrap = document.createElement("span");
    learnerWrap.className = "table-learner";
    const avatar = document.createElement("span");
    avatar.className = `avatar ${index % 2 ? "avatar-aria" : "avatar-you"}`;
    avatar.textContent = learner.name.charAt(0).toUpperCase();
    const details = document.createElement("span");
    const learnerName = document.createElement("strong");
    learnerName.textContent = learner.name;
    const level = document.createElement("small");
    level.textContent = learner.grade || "Grade not set";
    details.append(learnerName, level);
    learnerWrap.append(avatar, details);
    name.append(learnerWrap);
    const points = document.createElement("td");
    points.textContent = learner.points.toLocaleString();
    const badges = document.createElement("td");
    badges.textContent = learner.achievement_count.toLocaleString();
    const lessons = document.createElement("td");
    lessons.textContent = learner.lessons_completed.toLocaleString();
    [rank, name, points, badges, lessons].forEach((cell) => row.append(cell));
    tableBody.append(row);
  });
}

