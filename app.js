async function initializeApp() {
  try {
    curriculum = await api("/api/curriculum");
    populateCurriculumSelectors();
    if (inviteToken) {
      window.history.replaceState({}, "", `${window.location.pathname}${window.location.search}`);
      setAuthMode("invite-signup");
      document.querySelector("#auth-email").readOnly = true;
      const invite = await api("/api/invites/validate", {
        method: "POST",
        body: JSON.stringify({ token: inviteToken })
      });
      document.querySelector("#auth-email").value = invite.email;
      document.querySelector("#auth-subtitle").textContent =
        `Invited for ${invite.permissions.join(", ")} · ${invite.grades.join(", ")}. Use the invited email address.`;
    } else if (!isAdminPage) {
      setAuthMode("signin");
    }
    await refreshAuthStatus();
    if (!inviteToken && isAdminPage) {
      if (authStatus.adminConfigured) {
        setAuthMode("admin-signin");
      } else if (authStatus.setupEnabled) {
        setAuthMode("admin-setup");
      } else {
        setAuthMode("admin-signin");
        authError.textContent = "Admin setup is not configured. Ask the server owner to configure ADMIN_SETUP_KEY.";
        authError.hidden = false;
      }
    }
    const { user } = await api("/api/auth/me");
    if (user) {
      if (inviteToken && user.role === "student") {
        const accepted = await api("/api/auth/invites/accept", {
          method: "POST",
          body: JSON.stringify({ token: inviteToken })
        });
        inviteToken = null;
        await enterApp(accepted.user);
      } else {
        await enterApp(user);
      }
    }
  } catch (error) {
    authError.textContent = error.message;
    authError.hidden = false;
  }
}

